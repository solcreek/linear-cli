#!/usr/bin/env python3
"""The agent skill in skills/linearctl/: SKILL.md and references/, made from
SKILL.template.md, the linearctl section of AGENTS.md, and the binary's own
`describe` and `--help`, so the skill cannot drift from the commands.

    scripts/skill-docs.py write ./target/debug/linearctl   # rewrite the skill
    scripts/skill-docs.py check ./target/debug/linearctl   # exit 1 if it is stale

check also fails when AGENTS.md's "Mutating:" list differs from the commands
describe marks as mutating.
"""
import json
import os
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "linearctl"
REPO = "https://github.com/solcreek/linear-cli/blob/main/"


def linearctl(binary, *args):
    """Runs the binary as the golden tests do: no key, no stored state."""
    with tempfile.TemporaryDirectory(prefix="lc-skill-") as home:
        env = {k: v for k, v in os.environ.items() if not k.startswith(("LINEAR", "XDG_"))}
        env.update({"NO_COLOR": "1", "LINEARCTL_HOME": home, "HOME": home})
        p = subprocess.run([binary, *args], env=env, capture_output=True, text=True, check=True)
        return p.stdout


def leaves(cmd, path=()):
    """Every runnable command, as (path, describe entry), in describe's order."""
    path = path + (cmd["name"],)
    if not cmd["commands"]:
        yield path, cmd
    for sub in cmd["commands"]:
        yield from leaves(sub, path)


def agents_section():
    """AGENTS.md's linearctl section, its repository links made absolute."""
    text = (ROOT / "AGENTS.md").read_text()
    body = text.split("## linearctl\n", 1)[1].strip()
    return re.sub(r"\b(docs/[\w.-]+\.md)\b", lambda m: REPO + m.group(1), body)


def check_agents(commands):
    """AGENTS.md's list of mutating commands, against describe's."""
    text = (ROOT / "AGENTS.md").read_text()
    m = re.search(r"^- Mutating: (.*?)\. Run each", text, re.S | re.M)
    listed = set(re.findall(r"`([^`]+)`", m.group(1))) if m else set()
    actual = {" ".join(path) for path, c in commands if c.get("mutates")}
    problems = [f"AGENTS.md lists {c} as mutating; describe does not" for c in sorted(listed - actual)]
    problems += [f"AGENTS.md's Mutating: list lacks {c}" for c in sorted(actual - listed)]
    return problems


def help_text(binary, path):
    """A command's --help without the global flags SKILL.md lists once."""
    text = linearctl(binary, *path, "--help")
    return text.split("\nGlobal Flags:\n", 1)[0].rstrip() + "\n"


def build(binary):
    """The skill's files, {path relative to SKILL: text}."""
    d = json.loads(linearctl(binary, "describe"))
    commands = [(path, c) for top in d["commands"] for path, c in leaves(top)]
    groups = {}
    for path, c in commands:
        groups.setdefault(path[0], []).append((path, c))

    files = {}
    for group, cmds in groups.items():
        parts = [f"# linearctl {group}\n\n<!-- Generated by scripts/skill-docs.py from --help; do not edit. -->\n"]
        for path, c in cmds:
            name = " ".join(path)
            parts.append(f"\n## linearctl {name}\n\n```\n{help_text(binary, path)}```\n")
        files[f"references/{group}.md"] = "".join(parts)

    rows = ["| command | does | M |", "|---|---|---|"]
    for path, c in commands:
        args = " ".join(a["name"] if a["required"] else f"[{a['name']}]" for a in c["args"])
        usage = " ".join(["linearctl", *path] + ([args] if args else []))
        ref = f"references/{path[0]}.md"
        rows.append(f"| [`{usage}`]({ref}) | {c['summary'].rstrip('. ')} | {'M' if c.get('mutates') else ''} |")
    globals_ = ", ".join(f"`--{f['name']}`" for f in d["flags"] if f["name"] not in ("help", "version"))
    refs = "\n".join(f"- [{g}](references/{g}.md): {', '.join(' '.join(p[1:]) or g for p, _ in cmds)}"
                     for g, cmds in groups.items())

    template = (SKILL / "SKILL.template.md").read_text()
    files["SKILL.md"] = (
        template.replace("{{AGENTS}}", agents_section())
        .replace("{{COMMANDS}}", "\n".join(rows))
        .replace("{{GLOBAL_FLAGS}}", globals_)
        .replace("{{REFERENCES}}", refs)
    )
    leftover = re.findall(r"\{\{\w+\}\}", files["SKILL.md"])
    if leftover:
        sys.exit(f"skill-docs: SKILL.template.md has unknown placeholders: {', '.join(leftover)}")
    return files, check_agents(commands)


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("write", "check"):
        sys.exit(__doc__)
    mode, binary = sys.argv[1], sys.argv[2]
    files, problems = build(binary)
    existing = {str(p.relative_to(SKILL)) for p in SKILL.rglob("*.md") if p.name != "SKILL.template.md"}
    if mode == "write":
        for rel in existing - files.keys():
            (SKILL / rel).unlink()
        for rel, text in files.items():
            (SKILL / rel).parent.mkdir(parents=True, exist_ok=True)
            (SKILL / rel).write_text(text)
        print(f"wrote {len(files)} files in {SKILL.relative_to(ROOT)}")
    else:
        for rel in sorted(existing | files.keys()):
            p = SKILL / rel
            if rel not in files:
                problems.append(f"{rel} is not generated any more; run make skill")
            elif not p.exists() or p.read_text() != files[rel]:
                problems.append(f"{rel} is stale; run make skill")
    for p in problems:
        print(f"skill-docs: {p}", file=sys.stderr)
    if problems:
        sys.exit(1)
    if mode == "check":
        print(f"{len(files)} skill files are current")


if __name__ == "__main__":
    main()
